        public ?array $not_allowed = null,
        public ?array $mandatory_items = null,
        public ?array $booking_questions = null,
        public ?array $passenger_fields = null,
        public ?string $custom_info_before_booking = null,
        public ?string $other_info_before_booking = null,
        public ?array $raw_response = null,
        public float $review_rating = 0.0,
        public int $review_count = 0,
        public ?float $starting_price = null,
        public string $currency = 'EUR',

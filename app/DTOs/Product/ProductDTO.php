        public ?string $transportation_type = null,
        public bool $travels_to_different_city = false,
        public bool $skip_the_line = false,
        public ?string $skip_line_type = null,
        public bool $wheelchair_accessible = false,
        public ?string $meeting_point = null,
        public ?string $arrive_time = null,
        public ?string $places = null,
        public ?string $address_list = null,
        public ?string $customer_visits = null,
        public ?array $highlights = null,
        public ?array $inclusions = null,

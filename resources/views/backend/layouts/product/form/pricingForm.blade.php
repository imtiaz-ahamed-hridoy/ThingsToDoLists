                    @foreach(['USD','EUR','GBP','AUD','CAD'] as $curr)
                        <option value="{{ $curr }}" {{ old('price.defaultCurrency', $price->defaultCurrency ?? 'USD') === $curr ? 'selected' : '' }}>{{ $curr }}</option>
                    @endforeach
                </select>
            </div>
            <div class="col-md-4">
                 <label class="form-label">Base Price (Fallback) <span class="text-danger">*</span></label>
                 <input type="number" name="price[amount]" class="form-control" step="0.01" value="{{ old('price.amount', $price->amount ?? 0) }}" oninput="updatePricingJSON()" required>
            </div>
            <div class="col-md-4">
                <div class="form-check mt-4">
                    <input type="hidden" name="price[isPriceConverted]" value="0">
                    <input type="checkbox" name="price[isPriceConverted]" value="1" class="form-check-input" {{ old('price.isPriceConverted', $price->isPriceConverted ?? false) ? 'checked' : '' }}>

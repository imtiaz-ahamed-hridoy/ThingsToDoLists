@push('scripts')
<script>
window.pricingInitialized = window.pricingInitialized || false;

// Configuration
const PASSENGER_TYPES = [
    { type: 'ADULT', label: 'Adult', min: 18, max: 99 },
    { type: 'CHILD', label: 'Child', min: 3, max: 17 },
    { type: 'INFANT', label: 'Infant', min: 0, max: 2 }
];

// Main update function
function updatePricingJSON() {
    const jsonInput = document.getElementById('pricingJson');
    const currency = document.getElementById('currencySelector').value;
    
    // 1. Collect Default Rates
    const defaultPassengers = collectPassengerRates('defaultRatesContainer', currency);

    // 2. Collect Seasonal Rates
    const seasonalRates = [];
    document.querySelectorAll('.season-block').forEach(block => {
        const start = block.querySelector('.season-start')?.value;
        const end = block.querySelector('.season-end')?.value;
        
        if (start && end) {
            const passengers = collectPassengerRates(block.id, currency);
            if (passengers.length > 0) {
                seasonalRates.push({
                    startDate: start,
                    endDate: end,
                    rates: { passengers: passengers }
                });
            }
        }
    });

    // 3. Build Final Object
    const finalData = {
        passengers: defaultPassengers, // Main level for compatibility
        pricesByDateRange: seasonalRates
    };

    jsonInput.value = JSON.stringify(finalData);
}

// Helper to collect rates from a specific container
function collectPassengerRates(containerId, currency) {
    const container = document.getElementById(containerId);
    if (!container) return [];

    const rates = [];
    container.querySelectorAll('.passenger-row').forEach(row => {
        const type = row.dataset.type;
        const price = parseFloat(row.querySelector('.price-input').value);
        const minAge = parseInt(row.querySelector('.min-age').value);
        const maxAge = parseInt(row.querySelector('.max-age').value);

        // Check for tiers
        const tiers = [];
        row.querySelectorAll('.tier-row').forEach(tierRow => {
            const minPax = parseInt(tierRow.querySelector('.tier-min').value);
            const tierPrice = parseFloat(tierRow.querySelector('.tier-price').value);
            if (minPax && !isNaN(tierPrice)) {
                tiers.push({ minPassengersRequired: minPax, amount: tierPrice, currency: currency });
            }
        });

        if (!isNaN(price) || tiers.length > 0) {
           rates.push({
               type: type,
               price: !isNaN(price) ? { amount: price, currency: currency } : { amount: 0, currency: currency },
               ageRange: { min: minAge, max: maxAge },
               tieredPrices: tiers.length > 0 ? tiers : undefined
           });
        }
    });
    return rates;
}

// Render Functions
function renderPassengerRow(container, typeData, existingData = null) {
    const rowId = `row-${Math.random().toString(36).substr(2, 9)}`;
    const div = document.createElement('div');
    div.classList.add('card', 'mb-2', 'passenger-row');
    div.dataset.type = typeData.type;
    div.innerHTML = `
        <div class="card-body py-2 px-3">
            <div class="row g-2 align-items-center">
                <div class="col-12 col-md-2 fw-bold mb-2 mb-md-0">${typeData.label}</div>
                <div class="col-12 col-md-3 mb-2 mb-md-0">
                    <label class="d-md-none small text-muted mb-1">Price</label>
                    <div class="input-group input-group-sm">
                        <span class="input-group-text">$</span>
                        <input type="number" class="form-control price-input" placeholder="Price" step="0.01" 
                               value="${existingData?.price?.amount ?? ''}" oninput="updatePricingJSON()">
                    </div>
                </div>
                <div class="col-6 col-md-2 mb-2 mb-md-0">
                    <label class="d-md-none small text-muted mb-1">Min Age</label>
                    <input type="number" class="form-control form-control-sm min-age" placeholder="Min Age" 
                           value="${existingData?.ageRange?.min ?? typeData.min}" oninput="updatePricingJSON()">
                </div>
                <div class="col-6 col-md-2 mb-2 mb-md-0">
                    <label class="d-md-none small text-muted mb-1">Max Age</label>
                    <input type="number" class="form-control form-control-sm max-age" placeholder="Max Age" 
                           value="${existingData?.ageRange?.max ?? typeData.max}" oninput="updatePricingJSON()">
                </div>
                <div class="col-12 col-md-3 text-start text-md-end">
                    <button type="button" class="btn btn-link btn-sm text-decoration-none p-0 mt-2 mt-md-0" onclick="toggleTiers('${rowId}')">
                        <i class="fe fe-layers"></i> Tiered Pricing
                    </button>
                </div>
            </div>
            
            {{-- Tiers Container --}}
            <div id="${rowId}-tiers" class="mt-2 ps-3 border-start border-primary" style="display: ${existingData?.tieredPrices?.length ? 'block' : 'none'};">
                <small class="text-muted d-block mb-1">Group Discounts (Tiered Pricing)</small>
                <div class="tiers-list"></div>
                <button type="button" class="btn btn-sm btn-light text-primary mt-1" onclick="addTier('${rowId}')">+ Add Tier</button>
            </div>
        </div>
    `;
    div.id = rowId;
    container.appendChild(div);

    // Initial Tiers
    if (existingData?.tieredPrices) {
        existingData.tieredPrices.forEach(tier => addTier(rowId, tier));
    }
}

function toggleTiers(rowId) {
    const container = document.getElementById(`${rowId}-tiers`);
    container.style.display = container.style.display === 'none' ? 'block' : 'none';
}

function addTier(rowId, data = null) {
    const container = document.querySelector(`#${rowId}-tiers .tiers-list`);
    const div = document.createElement('div');
    div.classList.add('row', 'g-2', 'mb-1', 'tier-row', 'align-items-center');
    div.innerHTML = `
        <div class="col-12 col-md-5 mb-2 mb-md-0">
            <input type="number" class="form-control form-control-sm tier-min" placeholder="Min Pax (e.g. 5)" 
                   value="${data?.minPassengersRequired ?? ''}" oninput="updatePricingJSON()">
        </div>
        <div class="col-12 col-md-5 mb-2 mb-md-0">
            <input type="number" class="form-control form-control-sm tier-price" placeholder="Price per person" 
                   value="${data?.amount ?? ''}" oninput="updatePricingJSON()">
        </div>
        <div class="col-12 col-md-2 text-end text-md-start">
            <button type="button" class="btn btn-close btn-sm" onclick="this.closest('.tier-row').remove(); updatePricingJSON()"></button>
        </div>
    `;
    container.appendChild(div);
}

function addSeason(data = null) {
    const container = document.getElementById('seasonalRatesContainer');
    const seasonId = `season-${Math.random().toString(36).substr(2, 9)}`;
    
    const div = document.createElement('div');
    div.classList.add('card', 'mb-3', 'border-warning', 'season-block');
    div.id = seasonId;
    
    div.innerHTML = `
        <div class="card-header bg-warning-soft d-flex justify-content-between align-items-center py-2">
            <span class="fw-bold text-dark"><i class="fe fe-calendar"></i> Seasonal Rule</span>
            <button type="button" class="btn btn-danger btn-sm py-0" onclick="this.closest('.season-block').remove(); updatePricingJSON()">Remove</button>
        </div>
        <div class="card-body pt-3 pb-2">
            <div class="row g-2 mb-3">
                <div class="col-md-6">
                    <label class="small text-muted">Start Date</label>
                    <input type="date" class="form-control form-control-sm season-start" value="${data?.startDate ?? ''}" oninput="updatePricingJSON()">
                </div>
                <div class="col-md-6">
                    <label class="small text-muted">End Date</label>
                    <input type="date" class="form-control form-control-sm season-end" value="${data?.endDate ?? ''}" oninput="updatePricingJSON()">
                </div>
            </div>
            <div class="passengers-container" id="${seasonId}-passengers"></div>
        </div>
    `;
    container.appendChild(div);

    // Add passenger rows to this season
    const pContainer = div.querySelector(`#${seasonId}-passengers`);
    PASSENGER_TYPES.forEach(pt => {
        // Find existing data for this passenger type if loading
        const pData = data?.rates?.passengers?.find(p => p.type === pt.type);
        renderPassengerRow(pContainer, pt, pData);
    });
}

function initPricing() {
    if (window.pricingInitialized) return;
    window.pricingInitialized = true;

    const jsonInput = document.getElementById('pricingJson');
    const defaultContainer = document.getElementById('defaultRatesContainer');

    try {
        const data = JSON.parse(jsonInput.value || '{}');

        // 1. Initial Default Rows
        PASSENGER_TYPES.forEach(pt => {
            const pData = data.passengers?.find(p => p.type === pt.type);
            renderPassengerRow(defaultContainer, pt, pData);
        });

        // 2. Initial Seasons
        if (data.pricesByDateRange && Array.isArray(data.pricesByDateRange)) {
            data.pricesByDateRange.forEach(season => addSeason(season));
        }

    } catch (e) {
        console.error('Pricing Init Error', e);
        // Fallback: render empty default rows
        PASSENGER_TYPES.forEach(pt => renderPassengerRow(defaultContainer, pt));
    }
}

// Load on ready
if (document.readyState === 'loading') {
    document.addEventListener('DOMContentLoaded', initPricing);
} else {
    initPricing();
}
</script>

